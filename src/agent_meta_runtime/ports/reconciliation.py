"""Persistence operations used by the application reconciliation program."""

from typing import Any, Mapping, Protocol, Sequence


class ReconcilePersistence(Protocol):
    def execute(self, conn, envelope, mutator, *, deadline) -> dict: ...
    def migrate(self, txn, bindings: Sequence[Mapping[str, Any]]) -> None: ...
    def set_serving(self, txn, realm_id: str, revision: int, expected_cas: int) -> dict: ...
    def set_realized(self, txn, realm_id: str, revision: int, expected_cas: int) -> dict: ...
    def settle_harness(self, txn, realm_id: str, composition_id: str | None) -> dict: ...
    def fail_activation(self, txn, composition_id: str, reason_code: str) -> dict: ...
